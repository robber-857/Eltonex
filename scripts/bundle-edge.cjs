const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const handler = fs.readFileSync(path.join(root, 'supabase/functions/site-api/handler.mjs'), 'utf8');
const entry = fs.readFileSync(path.join(root, 'supabase/functions/site-api/index.ts'), 'utf8')
  .replace("import { createHandler } from './handler.mjs';", '');
